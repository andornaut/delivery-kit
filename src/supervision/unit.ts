// The optional systemd user unit for one game's resident runner. Rendering only reads the
// coordinator layout, the game's checkout and the caller's PATH; it never installs a unit or runs
// systemctl.
import { accessSync, constants, statSync } from "node:fs";
import { delimiter, dirname, isAbsolute, join } from "node:path";

import { EXIT_REFUSED } from "@andornaut/coordination-kit/build/shared";

import { PACKAGE } from "../compatibility.ts";

/** Host tools the runner's children need, in unit PATH order after the Node binary. */
export const SUPERVISION_TOOLS = ["gh", "docker", "git", "flock", "claude"] as const;
type SupervisionTool = (typeof SUPERVISION_TOOLS)[number];

/** Restart limits: five failed starts within ten minutes stop the unit. */
const START_LIMIT_INTERVAL_SECONDS = 600;
const START_LIMIT_BURST = 5;
const RESTART_SECONDS = 30;
/** An idle runner stops within seconds; a stop that takes longer is killed. */
const TIMEOUT_STOP_SECONDS = 120;
/** The exit status of `run` on SIGTERM. */
const SIGTERM_EXIT = 143;

export class UnitUnavailable extends Error {}

export interface RunnerUnitInput {
  readonly cliPath: string;
  readonly coordinatorRoot: string;
  readonly gameId: string;
  readonly gameName: string;
  readonly nodePath: string;
  /** PATH directories, in order, without duplicates. */
  readonly pathDirectories: readonly string[];
  readonly repo: string;
  readonly version: string;
}

function executable(path: string): boolean {
  try {
    accessSync(path, constants.X_OK);
    return statSync(path).isFile();
  } catch {
    return false;
  }
}

/**
 * Each tool's directory: the first absolute PATH entry holding an executable regular file of that
 * name. The entry is kept as listed, so a versioned install behind a stable link keeps working.
 */
export function resolveTools(
  env: NodeJS.ProcessEnv,
  tools: readonly SupervisionTool[] = SUPERVISION_TOOLS,
): { readonly directories: Readonly<Partial<Record<SupervisionTool, string>>>; missing: string[] } {
  const entries = (env.PATH ?? "").split(delimiter).filter((entry) => isAbsolute(entry));
  const directories: Partial<Record<SupervisionTool, string>> = {};
  const missing: string[] = [];
  for (const tool of tools) {
    const found = entries.find((entry) => executable(join(entry, tool)));
    if (found === undefined) {
      missing.push(tool);
    } else {
      directories[tool] = found;
    }
  }
  return { directories, missing };
}

/** The unit PATH: the Node directory, then each tool's directory, first occurrence kept. */
export function unitPath(nodePath: string, directories: readonly string[]): string[] {
  return [...new Set([dirname(nodePath), ...directories])];
}

/** The installed CLI the unit runs: the game's own pinned package. */
export function installedCli(repo: string): string {
  return join(repo, "node_modules", PACKAGE, "dist", "cli.js");
}

/** Reject values a unit file cannot carry literally; escape systemd specifiers. */
function literal(name: string, value: string): string {
  // eslint-disable-next-line no-control-regex
  if (/[\x00-\x1f\x7f"\\]/u.test(value)) {
    throw new UnitUnavailable(`${name} contains a character a unit file cannot carry: ${value}`);
  }
  return value.replaceAll("%", "%%");
}

/** One ExecStart word: `$` is escaped and a word with whitespace or `;` is quoted. */
function word(name: string, value: string): string {
  const text = literal(name, value).replaceAll("$", "$$");
  return /[\s;]/u.test(text) ? `"${text}"` : text;
}

/** The explicit unit text. Every path is absolute; nothing is resolved at service start. */
export function renderRunnerUnit(input: RunnerUnitInput): string {
  for (const [name, path] of [
    ["the coordinator root", input.coordinatorRoot],
    ["the game checkout", input.repo],
    ["the Node binary", input.nodePath],
    ["the installed CLI", input.cliPath],
    ...input.pathDirectories.map((directory) => ["a PATH directory", directory] as const),
  ] as const) {
    if (!isAbsolute(path)) {
      throw new UnitUnavailable(`${name} is not an absolute path: ${path}`);
    }
  }
  for (const directory of input.pathDirectories) {
    if (directory.includes(delimiter)) {
      throw new UnitUnavailable(`a PATH directory contains ${delimiter}: ${directory}`);
    }
  }
  const exec = [input.nodePath, input.cliPath, "run", "--game", input.gameId]
    .map((value) => word("ExecStart", value))
    .join(" ");
  const environment = (key: string, value: string): string =>
    `Environment="${key}=${literal(key, value)}"`;
  return [
    `# delivery-kit ${input.version} resident runner for ${input.gameId}.`,
    `# Generated by: delivery-kit runner unit --game ${input.gameId}`,
    "# Regenerate after a Node, tool or pin location change. It creates no timer.",
    "[Unit]",
    `Description=${literal("Description", `delivery-kit resident runner for ${input.gameName} (${input.gameId})`)}`,
    `StartLimitIntervalSec=${START_LIMIT_INTERVAL_SECONDS}`,
    `StartLimitBurst=${START_LIMIT_BURST}`,
    "",
    "[Service]",
    "Type=exec",
    `WorkingDirectory=${literal("WorkingDirectory", input.repo)}`,
    environment("DELIVERY_KIT_ROOT", input.coordinatorRoot),
    environment("PATH", input.pathDirectories.join(delimiter)),
    `ExecStart=${exec}`,
    "Restart=on-failure",
    `RestartSec=${RESTART_SECONDS}`,
    `SuccessExitStatus=${SIGTERM_EXIT}`,
    `RestartPreventExitStatus=${EXIT_REFUSED}`,
    "KillMode=mixed",
    "KillSignal=SIGTERM",
    `TimeoutStopSec=${TIMEOUT_STOP_SECONDS}`,
    "",
    "[Install]",
    "WantedBy=default.target",
    "",
  ].join("\n");
}
